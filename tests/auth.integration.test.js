const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const root = path.resolve(__dirname, '..');

test('账号登录会话固定工作台身份且教师拥有教学建设权限', async (t) => {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'cloudlab-auth-test-'));
  process.env.CLOUDLAB_DATA_FILE = path.join(temp, 'platform.json');
  process.env.CLOUDLAB_AUTH_FILE = path.join(temp, 'accounts.json');
  process.env.CLOUDLAB_AUTH_REQUIRED = 'true';
  process.env.CLOUDLAB_BOOTSTRAP_MAX_BYTES = '1500000';
  delete process.env.CLOUDLAB_TERMINAL_ENABLED;
  const { server } = require(path.join(root, 'local-server.js'));
  await new Promise((resolve, reject) => { server.once('error', reject); server.listen(0, '127.0.0.1', resolve); });
  t.after(async () => { await new Promise((resolve) => server.close(resolve)); fs.rmSync(temp, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const post = (url, body, cookie = '') => fetch(`${base}${url}`, { method: 'POST', headers: { 'Content-Type': 'application/json', ...(cookie ? { Cookie: cookie } : {}) }, body: JSON.stringify(body) });

  let response = await fetch(`${base}/api/auth/session`);
  assert.deepEqual((await response.json()).setupRequired, true);
  response = await fetch(`${base}/api/bootstrap`);
  assert.equal(response.status, 401);

  response = await post('/api/auth/setup', { username: 'platform-admin', name: '平台管理员', password: 'Admin-pass-2026' });
  assert.equal(response.status, 201);
  const adminCookie = response.headers.get('set-cookie').split(';')[0];
  response = await post('/api/auth/accounts', { username: 'teacher-a', name: '教师甲', password: 'Teacher-pass-2026', role: 'teacher' }, adminCookie);
  assert.equal(response.status, 201);
  response = await post('/api/auth/accounts', { username: 'student-a', name: '学生甲', password: 'Student-pass-2026', role: 'student' }, adminCookie);
  assert.equal(response.status, 201);
  response = await post('/api/auth/accounts', { username: 'student-b', name: '学生乙', password: 'Student-pass-2026', role: 'student' }, adminCookie);
  assert.equal(response.status, 201);

  response = await post('/api/auth/login', { username: 'teacher-a', password: 'Teacher-pass-2026' });
  assert.equal(response.status, 200);
  const teacherCookie = response.headers.get('set-cookie').split(';')[0];
  assert.equal(decodeURIComponent(teacherCookie.split('=').slice(1).join('=')).split('.').length, 2);
  const persistedAuth = JSON.parse(fs.readFileSync(process.env.CLOUDLAB_AUTH_FILE, 'utf8'));
  assert.ok(persistedAuth.sessionSecret.length >= 43);
  response = await fetch(`${base}/api/auth/session`, { headers: { Cookie: teacherCookie } });
  assert.equal((await response.json()).user.role, 'teacher');
  response = await post('/api/uploads', { name: 'teacher-resource.txt', mimeType: 'text/plain', contentBase64: Buffer.from('teacher can upload').toString('base64') }, teacherCookie);
  assert.equal(response.status, 201);
  const uploaded = await response.json();
  assert.equal(uploaded.uploadedBy, '教师甲');
  const course = { id: 'course-auth', name: '认证课程', visibility: '私有课程', allowRoleApplication: true, status: '已发布', stages: [{ id: 'stage-auth', labId: 'lab-auth' }], resources: [{ id: 'resource-auth', name: '课程资料', status: '已发布' }], assignments: [{ id: 'assignment-auth', title: '下载任务书', status: '已发布', assignmentAttachmentUrl: uploaded.url, assignmentAttachmentName: uploaded.name }], classrooms: [{ id: 'room-auth', name: '认证课堂', inviteCode: 'AUTH-2026', closed: false }], members: [], roleApplications: [], exams: [{ id: 'exam-auth', title: '实践考试', totalScore: 50, status: '已发布', labReferences: [{ labId: 'lab-auth', checkpointId: 'cp-2' }] }], submissions: [] };
  const lab = { id: 'lab-auth', name: '多关卡实验', state: '已发布', evaluationConfig: { fillBlankAnswer: 'print(\"完整正确答案\")', referenceAnswers: [{ name: '提示', content: '教师答案', deductionPercent: 20 }], tests: [{ id: 'hidden', name: '隐藏测试', visibility: 'hidden', target: 'secret.txt', expected: 'secret' }] }, checkpoints: [{ id: 'cp-1', name: '第一关' }, { id: 'cp-2', name: '第二关' }] };
  response = await fetch(`${base}/api/bootstrap`, { method: 'POST', headers: { 'Content-Type': 'application/json', Cookie: teacherCookie }, body: JSON.stringify({ version: 2, courses: [course], labs: [lab], settings: {} }) });
  assert.equal(response.status, 200);
  const updatedCourse = { ...course, summary: '教师增量修改课程内容', publicScope: '公开课程', publicReviewStatus: '待审核' };
  const deltaBody = { version: 2, revision: Date.now(), courses: [updatedCourse], labs: [], questionBank: [], deletedCourseIds: [], deletedLabIds: [], deletedQuestionIds: [], courseOrder: [course.id], labOrder: [lab.id], questionOrder: [] };
  assert.ok(Buffer.byteLength(JSON.stringify(deltaBody)) < Buffer.byteLength(JSON.stringify({ version: 2, courses: [course], labs: [lab], settings: {} })));
  response = await fetch(`${base}/api/bootstrap/delta`, { method: 'POST', headers: { 'Content-Type': 'application/json', Cookie: teacherCookie }, body: JSON.stringify(deltaBody) });
  assert.equal(response.status, 200);
  assert.equal((await response.json()).saved, true);
  response = await fetch(`${base}/api/bootstrap`, { headers: { Cookie: teacherCookie } });
  const afterCourseDelta = await response.json();
  assert.equal(afterCourseDelta.courses[0].summary, '教师增量修改课程内容');
  assert.equal(afterCourseDelta.courses[0].publicScope, '公开课程');
  response = await post('/api/auth/accounts', { username: 'forbidden', name: '无权限', password: 'Password-2026', role: 'student' }, teacherCookie);
  assert.equal(response.status, 403);

  response = await post('/api/auth/login', { username: 'student-a', password: 'Student-pass-2026' });
  const studentCookie = response.headers.get('set-cookie').split(';')[0];
  response = await post('/api/uploads', { name: 'forbidden.txt', mimeType: 'text/plain', contentBase64: Buffer.from('student cannot upload').toString('base64') }, studentCookie);
  assert.equal(response.status, 403);
  response = await fetch(`${base}/api/bootstrap`, { headers: { Cookie: studentCookie } });
  assert.equal((await response.json()).courses.length, 0);
  response = await post('/api/classrooms/join', { inviteCode: 'AUTH-2026' }, studentCookie);
  assert.equal(response.status, 200);
  assert.equal((await response.json()).courseId, 'course-auth');
  response = await fetch(`${base}/api/courses/course-auth/assignments/assignment-auth/attachment`, { headers: { Cookie: studentCookie } });
  assert.equal(response.status, 200);
  assert.match(response.headers.get('content-disposition'), /^attachment;/);
  assert.equal(await response.text(), 'teacher can upload');
  response = await post('/api/classrooms/role-application', { courseId: 'course-auth', requestedRole: '助教', reason: '协助批阅实验报告' }, studentCookie);
  assert.equal(response.status, 201);
  assert.equal((await response.json()).status, '待审核');
  response = await post('/api/student-progress/events', { kind: '评测', title: '提交正式评测', detail: '第二关通过', passed: true, score: 80, courseId: 'course-auth', labId: 'lab-auth', checkpointId: 'cp-2', examId: 'exam-auth' }, studentCookie);
  assert.equal(response.status, 403);
  const terminalGateway = require(path.join(root, 'terminal-gateway.js'));
  const originalRunLabTests = terminalGateway.runLabTests;
  terminalGateway.runLabTests = async () => ({ score: 80, passed: true, passingScore: 60, passPolicy: 'score-threshold', checks: [] });
  t.after(() => { terminalGateway.runLabTests = originalRunLabTests; });
  response = await fetch(`${base}/api/lab/test`, { method: 'POST', headers: { Cookie: studentCookie, 'X-Lab-Id': 'lab-auth', 'X-Checkpoint-Id': 'cp-2', 'X-Course-Id': 'course-auth', 'X-Exam-Id': 'exam-auth', 'X-Lab-Formal': 'true' } });
  assert.equal(response.status, 200);
  const evaluation = await response.json();
  const evaluationId = evaluation.evaluationId;
  assert.ok(evaluationId);
  assert.equal(evaluation.progressRecorded, true);
  assert.equal(evaluation.studentProgress.score, 80);
  response = await fetch(`${base}/api/bootstrap`, { headers: { Cookie: teacherCookie } });
  const teacherDataAfterEvaluation = await response.json();
  const studentDirectoryEntry = teacherDataAfterEvaluation.studentDirectory.find((item) => item.username === 'student-a');
  assert.match(studentDirectoryEntry.accountId, /^[0-9a-f-]{36}$/i);
  assert.deepEqual({ username: studentDirectoryEntry.username, name: studentDirectoryEntry.name, enabled: studentDirectoryEntry.enabled }, { username: 'student-a', name: '学生甲', enabled: true });
  assert.equal('passwordHash' in studentDirectoryEntry, false);
  assert.equal('salt' in studentDirectoryEntry, false);
  const recordedStudentProgress = Object.values(teacherDataAfterEvaluation.studentProgressByAccount);
  assert.equal(recordedStudentProgress.length, 1);
  assert.equal(recordedStudentProgress[0].score, 80);
  assert.equal(recordedStudentProgress[0].attempts, 1);
  assert.equal(recordedStudentProgress[0].gradeRecords[0].gradeType, 'exam');
  assert.equal(recordedStudentProgress[0].gradeRecords[0].studentNameSnapshot, '学生甲');
  assert.equal(recordedStudentProgress[0].gradeRecords[0].score, 40);
  assert.equal(recordedStudentProgress[0].gradeRecords[0].rawScore, 80);
  assert.equal(recordedStudentProgress[0].gradeRecords[0].maxScore, 50);
  assert.equal(teacherDataAfterEvaluation.courses[0].submissions[0].score, 40);
  assert.equal(teacherDataAfterEvaluation.courses[0].submissions[0].gradeType, 'exam');
  response = await fetch(`${base}/api/bootstrap/delta`, { method: 'POST', headers: { 'Content-Type': 'application/json', Cookie: teacherCookie }, body: JSON.stringify({ version: 2, revision: Date.now() + 1, courses: [{ ...updatedCourse, name: '认证课程（已修改）' }], labs: [], questionBank: [], deletedCourseIds: [], deletedLabIds: [], deletedQuestionIds: [], courseOrder: [course.id], labOrder: [lab.id], questionOrder: [] }) });
  assert.equal(response.status, 200);
  response = await fetch(`${base}/api/bootstrap`, { headers: { Cookie: teacherCookie } });
  const teacherDataAfterCourseEdit = await response.json();
  assert.equal(teacherDataAfterCourseEdit.courses[0].name, '认证课程（已修改）');
  assert.equal(teacherDataAfterCourseEdit.courses[0].submissions[0].score, 40);
  assert.equal(Object.values(teacherDataAfterCourseEdit.studentProgressByAccount)[0].score, 80);
  response = await post('/api/student-progress/events', { kind: '评测', title: '提交正式评测', detail: '第二关通过', passed: false, score: 0, evaluationId, courseId: 'course-auth', labId: 'lab-auth', checkpointId: 'cp-2', examId: 'exam-auth' }, studentCookie);
  assert.equal(response.status, 200);
  response = await post('/api/student-progress/events', { kind: '评测', title: '重复提交', evaluationId, labId: 'lab-auth', checkpointId: 'cp-2' }, studentCookie);
  assert.equal(response.status, 403);
  response = await fetch(`${base}/api/bootstrap`, { headers: { Cookie: studentCookie } });
  const data = await response.json();
  assert.equal(data.studentDirectory, undefined);
  assert.equal(data.labs[0].evaluationConfig.fillBlankAnswer, undefined);
  assert.equal(data.labs[0].evaluationConfig.referenceAnswers[0].content, undefined);
  assert.equal(data.labs[0].evaluationConfig.tests[0].target, undefined);
  assert.equal(data.courses[0].submissions[0].studentName, '学生甲');
  assert.equal(data.courses[0].submissions[0].score, 40);
  assert.equal(data.studentProgress.resourceProgress['lab:lab-auth'].completedSubtasks, 1);
  assert.equal(data.studentProgress.resourceProgress['lab:lab-auth'].totalSubtasks, 2);
  assert.equal(data.studentProgress.attempts, 1);
  response = await post('/api/lab/answer', { labId: 'lab-auth', checkpointId: 'cp-2', index: 0 }, studentCookie);
  assert.equal(response.status, 200);
  assert.equal((await response.json()).content, '教师答案');
  response = await fetch(`${base}/api/lab/test`, { method: 'POST', headers: { Cookie: studentCookie, 'X-Lab-Id': 'lab-auth', 'X-Checkpoint-Id': 'cp-2', 'X-Course-Id': 'course-auth', 'X-Exam-Id': 'exam-auth', 'X-Lab-Formal': 'true' } });
  const deducted = await response.json();
  assert.equal(deducted.score, 60);
  assert.equal(deducted.passed, true);
  response = await fetch(`${base}/api/lab/test`, { method: 'POST', headers: { Cookie: studentCookie, 'X-Lab-Id': 'lab-auth', 'X-Checkpoint-Id': 'cp-2', 'X-Course-Id': 'course-auth', 'X-Lab-Formal': 'true' } });
  const regularEvaluation = await response.json();
  assert.equal(regularEvaluation.progressRecorded, true);
  assert.equal(regularEvaluation.studentProgress.gradeRecords[0].gradeType, 'regular');
  assert.equal(regularEvaluation.studentProgress.gradeRecords[0].score, 60);
  assert.equal(regularEvaluation.studentProgress.gradeRecords[1].gradeType, 'exam');
  response = await post('/api/auth/login', { username: 'student-b', password: 'Student-pass-2026' });
  const otherCookie = response.headers.get('set-cookie').split(';')[0];
  response = await post('/api/student-progress/events', { kind: '评测', title: '冒用凭据', evaluationId: deducted.evaluationId, labId: 'lab-auth', checkpointId: 'cp-2', courseId: 'course-auth', examId: 'exam-auth' }, otherCookie);
  assert.equal(response.status, 403);
  response = await fetch(`${base}/api/student-progress`, { headers: { Cookie: otherCookie } });
  assert.equal((await response.json()).score, null);
  response = await fetch(`${base}/api/bootstrap`, { headers: { Cookie: otherCookie } });
  assert.equal((await response.json()).labs.length, 0);
  response = await fetch(`${base}/api/lab/files`, { headers: { Cookie: otherCookie, 'X-Lab-Id': 'lab-auth' } });
  assert.equal(response.status, 403);
  response = await post('/api/lab/execute', { labId: 'lab-auth', command: 'pwd' }, otherCookie);
  assert.equal(response.status, 403);
  response = await fetch(`${base}/api/lab/status?labId=lab-auth`, { headers: { Cookie: otherCookie } });
  assert.equal(response.status, 403);
  response = await post('/api/lab/reset', {}, otherCookie);
  assert.equal(response.status, 403);
  response = await post('/api/lab/answer', { labId: 'lab-auth', checkpointId: 'cp-2', index: 0 }, otherCookie);
  assert.equal(response.status, 403);
  response = await post('/api/messages', { courseId: 'course-auth', subject: '越权', content: '不应发送' }, otherCookie);
  assert.equal(response.status, 403);
  response = await post('/api/student-progress/resources', { courseId: 'course-auth', resourceId: 'resource-auth', status: '已完成' }, otherCookie);
  assert.equal(response.status, 403);
  response = await fetch(`${base}/api/bootstrap`, { method: 'PUT', headers: { 'Content-Type': 'application/json', Cookie: studentCookie }, body: JSON.stringify({ version: 2, courses: [], labs: [], settings: {} }) });
  assert.equal(response.status, 403);
  response = await fetch(`${base}/accounts.json`);
  assert.equal(response.status, 403);

  const largeSaveBody = JSON.stringify({ version: 2, revision: Date.now(), courses: [course], labs: [lab], questionBank: [], settings: { largeTemplateProbe: 'x'.repeat(1_100_000) } });
  assert.ok(Buffer.byteLength(largeSaveBody) > 1_000_000);
  response = await fetch(`${base}/api/bootstrap`, { method: 'POST', headers: { 'Content-Type': 'application/json', Cookie: teacherCookie }, body: largeSaveBody });
  assert.equal(response.status, 200);
  assert.equal((await response.json()).saved, true);

  const oversizedSaveBody = JSON.stringify({ version: 2, revision: Date.now() + 1, courses: [course], labs: [lab], questionBank: [], settings: { largeTemplateProbe: 'x'.repeat(1_600_000) } });
  response = await fetch(`${base}/api/bootstrap`, { method: 'POST', headers: { 'Content-Type': 'application/json', Cookie: teacherCookie }, body: oversizedSaveBody });
  assert.equal(response.status, 413);
  assert.match((await response.json()).message, /请求体不能超过/);
});
